void	ft_rev_int_tab(int *tab, int size)
{
	int	tmp;

	while (size > 1)
	{
		tmp = tab[0];
		tab[0] = tab[size - 1];
		tab[size - 1] = tmp;
		tab++;
		size -= 2;
	}
}
